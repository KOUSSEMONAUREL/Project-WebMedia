// Overrides for the closed set of UI labels. These are short, ambiguous words
// ("Jeux", "Films", "À propos") that machine translation gets wrong out of
// context ("Games played", "Movie", "Who we are"). Free MT endpoints are also
// rate-limited, so quality would otherwise fluctuate with whichever engine
// answers. Keys are normalized: lowercase + accents stripped, so "Séries" and
// "Series" share one entry. Anything absent here falls through to live MT.

export type OverrideLang =
  | 'english'
  | 'spanish'
  | 'german'
  | 'italian'
  | 'portuguese'
  | 'japanese'
  | 'korean'
  | 'chinese_simplified'
  | 'russian'
  | 'arabic'
  | 'dutch'
  | 'polish'
  | 'turkish'
  | 'swedish'

export function normalizeKey(input: string): string {
  return input
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/\s+/g, ' ')
    .trim()
}

