const INDEXED = new Map<string, Map<string, string>>()

function indexFor(lang: string): Map<string, string> | undefined {
  if (lang === 'french') return undefined
  const cached = INDEXED.get(lang)
  if (cached) return cached
  const table = RAW[lang as OverrideLang]
  if (!table) return undefined
  const map = new Map<string, string>()
  for (const [key, value] of Object.entries(table)) map.set(normalizeKey(key), value)
  INDEXED.set(lang, map)
  return map
}

export function getOverride(lang: string, text: string): string | undefined {
  return indexFor(lang)?.get(normalizeKey(text))
}

